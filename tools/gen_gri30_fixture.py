#!/usr/bin/env python3
"""emit the cantera checkpoint fixture for the gri-mech 3.0 thermochemistry.

the fixture is a set of (species, temperature, cp, h, s) values taken
straight from cantera's own evaluation of the mechanism. the rust side
evaluates the generated polynomial table and must reproduce every one
of them to a tight tolerance. that closes the loop between the
transcription and the reference implementation without leaving the
comparison to anybody's arithmetic by hand.

cantera reports cp, h and s on a molar basis (J/(kmol K), J/kmol and
J/(kmol K)). the polynomial tables are likewise divided by a gas
constant in j per kmol-kelvin, so the two bases agree directly.

usage: env -u PYTHONPATH /usr/bin/python3.12 tools/gen_gri30_fixture.py
"""

from __future__ import annotations

import json
import pathlib
import sys

MECHANISM = (
    pathlib.Path.home()
    / ".local/lib/python3.12/site-packages/cantera/data/gri30.yaml"
)
OUTPUT = pathlib.Path(__file__).resolve().parents[1] / (
    "crates/nufor-core/src/gri30_fixture.rs"
)
TEMPERATURES = [300.0, 700.0, 1500.0, 2500.0, 3500.0]


def rust_float(value: float) -> str:
    text = repr(float(value))
    if "e" in text or "E" in text:
        mantissa, _, exponent = text.partition("e")
        if "." not in mantissa:
            mantissa += ".0"
        sign = "+" if not exponent.startswith("-") else "-"
        return "%se%s%d" % (mantissa, sign, int(exponent.lstrip("+-")))
    if "." not in text:
        text += ".0"
    return text


def main() -> int:
    sys.path.insert(0, str(MECHANISM.parent.parent.parent))
    try:
        import cantera as ct
    except ImportError as exc:  # pragma: no cover - environment check
        raise SystemExit("cantera is needed under python3.12: %s" % exc)

    gas = ct.Solution(str(MECHANISM))
    names = list(gas.species_names)

    rows = []
    for temperature in TEMPERATURES:
        for index, name in enumerate(names):
            # the species-level thermodynamic model is queried, not the
            # mixture. a mixture of one dominant species still carries
            # trace fractions of the other fifty-two, and those bring
            # a mixing term into the entropy that has nothing to do with
            # the polynomial being checked.
            thermo = gas.species(name).thermo
            rows.append(
                (
                    index,
                    temperature,
                    float(thermo.cp(temperature)),
                    float(thermo.h(temperature)),
                    float(thermo.s(temperature)),
                )
            )

    out = []
    out.append("//! cantera checkpoints for the gri-mech 3.0 thermochemistry.")
    out.append("//!")
    out.append("//! generated by tools/gen_gri30_fixture.py. each row holds")
    out.append("//! the species index, the temperature, and cantera's own")
    out.append("//! molar cp, enthalpy and entropy at one atmosphere.")
    out.append("//! the rust side must reproduce every row.")
    out.append("")
    out.append("/// the checkpoints: (species, temperature K, cp, h, s),")
    out.append("/// cp and s in j/(kmol k), h in j/kmol.")
    out.append("pub struct Checkpoint {")
    out.append("    pub species: usize,")
    out.append("    pub temperature: f64,")
    out.append("    pub cp_mole: f64,")
    out.append("    pub enthalpy_mole: f64,")
    out.append("    pub entropy_mole: f64,")
    out.append("}")
    out.append("")
    out.append("/// the checkpoint table.")
    out.append("pub const CHECKPOINTS: [Checkpoint; %d] = [" % len(rows))
    for index, temperature, cp, enthalpy, entropy in rows:
        out.append(
            "    Checkpoint { species: %d, temperature: %s, cp_mole: %s, "
            "enthalpy_mole: %s, entropy_mole: %s },"
            % (
                index,
                rust_float(temperature),
                rust_float(cp),
                rust_float(enthalpy),
                rust_float(entropy),
            )
        )
    out.append("];")
    out.append("")

    OUTPUT.write_text("\n".join(out), encoding="utf-8")
    print("wrote %s" % OUTPUT)
    print("%d checkpoints over %d species" % (len(rows), len(names)))

    # keep a json twin outside the repository for quick inspection.
    scratch = pathlib.Path("/tmp/gri30_fixture.json")
    scratch.write_text(
        json.dumps(
            [
                {
                    "species": index,
                    "temperature": temperature,
                    "cp_mole": cp,
                    "enthalpy_mole": enthalpy,
                    "entropy_mole": entropy,
                }
                for index, temperature, cp, enthalpy, entropy in rows
            ],
            indent=1,
        ),
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
