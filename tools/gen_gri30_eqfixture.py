#!/usr/bin/env python3
"""generate the equilibrium constant fixture for GRI-Mech 3.0.

the rust side derives the equilibrium constant from the NASA-7
thermodynamic polynomials, integrating the partition of gibbs energy
between the standard state and the temperature. cantera derives the same
quantity from its own thermochemistry. comparing the two on every
reaction at every sampled temperature checks the reversible-rate
machinery against an independent implementation.

cantera's reaction list is the expanded one: three-body reactions are
split per collider and repeated reactions are copied out, so it holds
325 entries rather than the mechanism's 89 numbered lines. that is fine
here, because this fixture is a thermodynamic check and cares only
about each reaction's stoichiometry, not about how the kinetics are
laid out.

cantera's constant is the concentration-form one, with concentrations in
mol/cm3, so the rust side converts its mol/m3 value into the same units
before comparing.

the standard-state convention is spelt out here because it is where a
comparison can silently go wrong:

    Kp = exp(-dg0 / (r t)), with dg0 the standard-state gibbs energy
         difference at p0 = 101325 pa
    kc = kp * (p0 / (r t)) ** dn

with dn the change in molecule count. cantera uses mol/cm3, so the
rust side divides its mol/m3 constant by 1000 for each unit of dn.

usage: env -u PYTHONPATH /usr/bin/python3.12 tools/gen_gri30_eqfixture.py
"""

from __future__ import annotations

import hashlib
import math
import pathlib
import sys

sys.path.insert(0, "/home/ebarleb/.local/lib/python3.12/site-packages")
import cantera as ct  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]
CORE = ROOT / "crates" / "nufor-core" / "src"
CANONICAL_YAML = pathlib.Path(
    "/home/ebarleb/.local/lib/python3.12/site-packages/cantera/data/gri30.yaml"
)
EXPECTED_SHA256 = (
    "06650b1e0ee0012f6903d5328b1bb218cb6007d07f8ebe375d18f24811039345"
)
TEMPERATURES = (300.0, 500.0, 900.0, 1500.0, 2500.0, 3500.0)


def rust_float(value: float) -> str:
    text = repr(float(value))
    return text


def main() -> int:
    digest = hashlib.sha256(CANONICAL_YAML.read_bytes()).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit(
            "canonical gri30.yaml digest moved: %s, refusing to regenerate" % digest
        )

    gas = ct.Solution(str(CANONICAL_YAML))
    names = list(gas.species_names)
    index = {name: i for i, name in enumerate(names)}

    reactions = []
    for r, rxn in enumerate(gas.reactions()):
        reactants = {k: float(v) for k, v in rxn.reactants.items()}
        products = {k: float(v) for k, v in rxn.products.items()}
        for carrier in ("M", "m"):
            reactants.pop(carrier, None)
            products.pop(carrier, None)
        delta_nu = sum(products.values()) - sum(reactants.values())
        reactions.append(
            {
                "index": r,
                "reactants": sorted((index[k], v) for k, v in reactants.items()),
                "products": sorted((index[k], v) for k, v in products.items()),
                "delta_nu": delta_nu,
                "third_body": bool(rxn.third_body),
                "reversible": bool(rxn.reversible),
                "equation": rxn.equation,
            }
        )

    samples = []
    for r, rxn in enumerate(gas.reactions()):
        if not reactions[r]["reversible"]:
            continue
        for temperature in TEMPERATURES:
            gas.TP = temperature, 101325.0
            kc = float(gas.equilibrium_constants[r])
            if not math.isfinite(kc) or kc <= 0.0:
                continue
            samples.append((r, temperature, math.log(kc)))

    lines = [
        "//! GRI-Mech 3.0 equilibrium constants from cantera, generated by",
        "//! tools/gen_gri30_eqfixture.py. do not edit by hand.",
        "//!",
        "//! the constant is the concentration form in (mol/l)**delta_nu, the",
        "//! basis cantera reports. the reaction stoichiometry itself lives in",
        "//! `gri30_generated.rs`, so this file carries only the samples.",
        "",
        "/// one sampled equilibrium constant.",
        "pub struct Sample {",
        "    /// the reaction's index.",
        "    pub reaction: usize,",
        "    /// the temperature in kelvin.",
        "    pub temperature: f64,",
        "    /// the natural log of the concentration-form constant.",
        "    pub ln_kc: f64,",
        "}",
        "",
        "/// the sampled equilibrium constants.",
        "pub static SAMPLES: &[Sample] = &[",
    ]
    for reaction, temperature, ln_kc in samples:
        lines.append(
            "    Sample { reaction: %d, temperature: %s, ln_kc: %s },"
            % (reaction, rust_float(temperature), rust_float(ln_kc))
        )
    lines.append("];")
    lines.append("")
    lines.append("/// the source digest the fixture was generated from.")
    lines.append('pub const SOURCE_SHA256: &str = "%s";' % digest)
    lines.append("")
    (CORE / "gri30_eq_fixture.rs").write_text("\n".join(lines))

    print(
        "species %d, reactions %d, samples %d"
        % (len(names), len(reactions), len(samples))
    )
    print("wrote gri30_eq_fixture.rs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
