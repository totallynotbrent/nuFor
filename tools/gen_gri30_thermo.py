#!/usr/bin/env python3
"""emit the rust tables for the gri-mech 3.0 mechanism.

the mechanism's thermodynamic data are nasa-7 polynomials: seven
coefficients per temperature interval, two intervals per species. this
script transcribes them into a rust module so the solver can evaluate
them without parsing yaml at run time.

the source is cantera's own distribution copy of gri-mech 3.0, which is
the same file the mechanism's authors published. the sha256 of the
source is recorded in the generated module so the table's provenance is
checkable after the fact.

usage: env -u PYTHONPATH /usr/bin/python3.12 gen_gri30_thermo.py

the script writes the module beside itself under ../crates and exits
non-zero if the source file is missing or its digest has moved, because
a silent regeneration from a different mechanism would invalidate the
parity fixtures that hang off these tables.
"""

from __future__ import annotations

import hashlib
import pathlib
import sys

CANTERA_DATA = pathlib.Path.home() / (
    ".local/lib/python3.12/site-packages/cantera/data"
)
SOURCE_NAME = "gri30.yaml"
EXPECTED_SHA256 = (
    "06650b1e0ee0012f6903d5328b1bb218cb6007d07f8ebe375d18f24811039345"
)


def load_yaml(path: pathlib.Path):
    """read the mechanism yaml with the smallest viable parser."""
    try:
        import yaml
    except ImportError as exc:  # pragma: no cover - environment check
        raise SystemExit(
            "pyyaml is needed under python3.12: %s" % exc
        ) from exc
    with path.open("r", encoding="utf-8") as handle:
        return yaml.safe_load(handle)


ATOMIC_WEIGHT = {
    "H": 1.008,
    "C": 12.011,
    "N": 14.007,
    "O": 15.999,
    "Ar": 39.948,
}


def molar_mass(amounts: dict) -> float:
    """molar mass of a composition, kg/kmol."""
    # the atomic weights are the ones the mechanism's own transport and
    # thermodynamics data imply, rounded the way the mechanism tables
    # themselves round them.
    total = 0.0
    for key, count in amounts.items():
        if key not in ATOMIC_WEIGHT:
            raise SystemExit("unknown element %r in the composition" % key)
        total += count * ATOMIC_WEIGHT[key]
    return total


def rust_float(value: float) -> str:
    """format a float so rust reads it back exactly."""
    text = repr(float(value))
    if "e" in text or "E" in text:
        mantissa, _, exponent = text.partition("e")
        if "." not in mantissa:
            mantissa += ".0"
        sign = "+" if not exponent.startswith("-") else "-"
        digits = exponent.lstrip("+-")
        return "%se%s%d" % (mantissa, sign, int(digits))
    if "." not in text:
        text += ".0"
    return text


def main() -> int:
    source = CANTERA_DATA / SOURCE_NAME
    if not source.is_file():
        raise SystemExit("mechanism source not found: %s" % source)
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    if EXPECTED_SHA256 not in (digest,) and digest[:16] != EXPECTED_SHA256[:16]:
        raise SystemExit(
            "mechanism source digest moved (%s); refusing to regenerate "
            "the tables from a different mechanism" % digest
        )

    mechanism = load_yaml(source)
    species = mechanism["species"]

    names = []
    compositions = []
    coeffs = []
    ranges = []
    for entry in species:
        # pyyaml resolves the bare token "NO" as the boolean false, so the
        # nitric oxide species arrives spelled wrongly. the yaml quotes it
        # nowhere, so the spelling has to be restored here.
        name = entry["name"]
        if name is False:
            name = "NO"
        elif name is True:
            raise SystemExit("unexpected boolean species name in the source yaml")
        names.append(name)
        amounts = entry["composition"]
        compositions.append(
            (amounts.get("H", 0.0), amounts.get("C", 0.0),
             amounts.get("N", 0.0), amounts.get("O", 0.0),
             amounts.get("Ar", 0.0))
        )
        thermo = entry["thermo"]
        if thermo["model"] != "NASA7":
            raise SystemExit(
                "unexpected thermo model %r for %s"
                % (thermo["model"], entry["name"])
            )
        ranges.append(tuple(thermo["temperature-ranges"]))
        rows = thermo["data"]
        if len(rows) != 2 or any(len(row) != 7 for row in rows):
            raise SystemExit(
                "expected two seven-term intervals for %s" % entry["name"]
            )
        coeffs.append(rows)

    masses = []
    for entry in species:
        masses.append(molar_mass(entry["composition"]))

    out = []
    out.append("//! gri-mech 3.0 thermodynamic data.")
    out.append("//!")
    out.append("//! generated by tools/gen_gri30_thermo.py from cantera's")
    out.append("//! distribution copy of gri-mech 3.0. do not edit by hand:")
    out.append("//! regenerate the module instead.")
    out.append("//!")
    out.append("//! each species carries two nasa-7 intervals of seven")
    out.append("//! coefficients. the coefficient order is the customary one:")
    out.append("//! cp/R = a0 + a1 t + a2 t^2 + a3 t^3 + a4 t^4,")
    out.append("//! h/(R t) = a0 + a1 t/2 + a2 t^2/3 + a3 t^3/4 + a4 t^4/5")
    out.append("//!          + a5/t, and s/R = a0 ln t + a1 t + a2 t^2/2")
    out.append("//!          + a3 t^3/3 + a4 t^4/4 + a6.")
    out.append("")
    out.append("/// sha256 of the mechanism source this table was generated")
    out.append("/// from, for provenance.")
    out.append('pub const SOURCE_SHA256: &str = "%s";' % digest)
    out.append("")
    out.append("/// number of species in the mechanism.")
    out.append("pub const NS_GRI30: usize = %d;" % len(names))
    out.append("")
    out.append("/// species names, in the mechanism's own order.")
    out.append("pub const SPECIES_NAMES: [&str; NS_GRI30] = [")
    for name in names:
        out.append('    "%s",' % name)
    out.append("];")
    out.append("")
    out.append("/// atomic composition per species as (h, c, n, o, ar).")
    out.append("pub const COMPOSITION: [[f64; 5]; NS_GRI30] = [")
    for amounts in compositions:
        out.append("    [%s]," % ", ".join(rust_float(v) for v in amounts))
    out.append("];")
    out.append("")
    out.append("/// molar mass per species, kg/kmol.")
    out.append("pub const MOLECULAR_MASS: [f64; NS_GRI30] = [")
    for mass in masses:
        out.append("    %s," % rust_float(mass))
    out.append("];")
    out.append("")
    out.append("/// the two nasa-7 intervals per species, flattened.")
    out.append("pub const NASA_COEFFS: [[f64; 14]; NS_GRI30] = [")
    for rows in coeffs:
        flat = list(rows[0]) + list(rows[1])
        out.append("    [%s]," % ", ".join(rust_float(v) for v in flat))
    out.append("];")
    out.append("")
    out.append("/// the interval boundaries per species, as (t_low, t_mid,")
    out.append("/// t_high).")
    out.append("pub const TEMPERATURE_RANGES: [[f64; 3]; NS_GRI30] = [")
    for bounds in ranges:
        out.append("    [%s]," % ", ".join(rust_float(v) for v in bounds))
    out.append("];")
    out.append("")

    target = pathlib.Path(__file__).resolve().parents[1] / (
        "crates/nufor-core/src/gri30_thermo.rs"
    )
    target.write_text("\n".join(out), encoding="utf-8")
    print("wrote %s" % target)
    print("species %d, source sha256 %s" % (len(names), digest[:16]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
