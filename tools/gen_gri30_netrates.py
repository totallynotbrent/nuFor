#!/usr/bin/env python3
"""generate the net-rate fixture for GRI-Mech 3.0.

the rust side computes the net rate of progress of every reaction from
its own tables, using the equilibrium constant derived from the NASA-7
polynomials for the backward branch. this fixture records what cantera
computes for the same mixtures and temperatures, so the two can be
compared reaction by reaction.

cantera's expanded reaction list is used as it stands: three-body
reactions appear once per collider and repeated reactions are copied
out. the stoich pointers in the fixture refer to that expanded ordering,
which is the ordering the generated mechanism table uses.

the recorded mixtures are made of the first eight species of the
mechanism, so every reaction contributes something rather than sitting
at a trivially zero rate.

usage: env -u PYTHONPATH /usr/bin/python3.12 tools/gen_gri30_netrates.py
"""

from __future__ import annotations

import hashlib
import math
import pathlib
import sys

sys.path.insert(0, "/home/ebarleb/.local/lib/python3.12/site-packages")
import cantera as ct  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]
CORE = ROOT / "crates" / "nufor-core" / "src"
CANONICAL_YAML = pathlib.Path(
    "/home/ebarleb/.local/lib/python3.12/site-packages/cantera/data/gri30.yaml"
)
EXPECTED_SHA256 = (
    "06650b1e0ee0012f6903d5328b1bb218cb6007d07f8ebe375d18f24811039345"
)
CASES = (
    (800.0, 101325.0),
    (1200.0, 101325.0),
    (1800.0, 101325.0),
    (2500.0, 505625.0),
    (3200.0, 1013250.0),
)
FRACTIONS = (
    (0.30, 0.20, 0.18, 0.12, 0.10, 0.06, 0.03, 0.01),
    (0.10, 0.25, 0.20, 0.15, 0.12, 0.08, 0.06, 0.04),
    (0.45, 0.10, 0.15, 0.10, 0.08, 0.06, 0.04, 0.02),
    (0.05, 0.35, 0.25, 0.15, 0.08, 0.07, 0.03, 0.02),
    (0.55, 0.15, 0.10, 0.08, 0.05, 0.04, 0.02, 0.01),
)


def rust_float(value: float) -> str:
    return repr(float(value))



def scaled_fractions(fractions):
    """scale the eight fractions so they occupy ninety percent."""
    total = sum(fractions)
    return [value * 0.9 / total for value in fractions]


def full_composition(scaled, species_count, gas):
    """the first eight species' fractions, plus a tail over the rest.

    the eight heavy species hold ninety percent of the mixture, and the
    remaining tenth is spread over every other species on a geometric
    decay. that way no species is absent, so every reaction of the
    mechanism has its participants present and contributes a rate that
    can actually be compared. leaving the tail empty would park most of
    the mechanism at a trivially zero rate.
    """
    composition = [0.0] * species_count
    for index, value in enumerate(scaled):
        composition[index] = value
    argon = gas.species_index("AR")
    if argon is None:
        raise SystemExit("argon is missing from the mechanism")
    tail = 0.1
    composition[argon] = tail
    others = [
        index
        for index in range(species_count)
        if index not in range(len(scaled)) and index != argon
    ]
    if others:
        decay = 0.4
        weights = [decay ** rank for rank in range(len(others))]
        total = sum(weights)
        for index, weight in zip(others, weights):
            composition[index] = tail * weight / total
    total_fraction = sum(composition)
    return [value / total_fraction for value in composition]


def main() -> int:
    digest = hashlib.sha256(CANONICAL_YAML.read_bytes()).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit("source digest moved: %s" % digest)

    gas = ct.Solution(str(CANONICAL_YAML))
    molecules = gas.n_species
    n_cases = len(CASES)
    n_fractions = len(FRACTIONS)

    lines = [
        "//! GRI-Mech 3.0 net rates of progress from cantera, generated by",
        "//! tools/gen_gri30_netrates.py. do not edit by hand.",
        "//!",
        "//! each case gives a temperature, a pressure and a mole fraction",
        "//! vector for the first eight species. the rates are cantera's own",
        "//! net rates of progress for the expanded reaction list.",
        "",
        "/// one evaluated mixture.",
        "pub struct Mixture {",
        "    /// the temperature in kelvin.",
        "    pub temperature: f64,",
        "    /// the pressure in pascals.",
        "    pub pressure: f64,",
        "    /// the mole fractions of the first eight species.",
        "    pub major_fractions: [f64; 8],",
        "    /// the densities of every species in kmol/m3.",
        "    pub densities: [f64; %d]," % molecules,
        "}",
        "",
        "/// the evaluated mixtures.",
        "pub static MIXTURES: &[Mixture] = &[",
    ]

    count = 0
    for case_index, (temperature, pressure) in enumerate(CASES):
        fractions = scaled_fractions(FRACTIONS[case_index % n_fractions])
        composition = full_composition(fractions, molecules, gas)
        gas.TPX = temperature, pressure, composition
        # cantera's concentrations are already kmol/m3, which is the basis
        # the generated mechanism tables use.
        densities = [gas.concentrations[s] for s in range(molecules)]
        lines.append("    Mixture {")
        lines.append("        temperature: %s," % rust_float(temperature))
        lines.append("        pressure: %s," % rust_float(pressure))
        lines.append(
            "        major_fractions: [%s],"
            % ", ".join(rust_float(f) for f in fractions)
        )
        lines.append(
            "        densities: [%s],"
            % ", ".join(rust_float(d) for d in densities)
        )
        lines.append("    },")
        count += 1

    lines.append("];")
    lines.append("")
    lines.append("/// the cantera net rates of progress, flattened case-major.")
    lines.append("///")
    lines.append("/// the outer dimension is the mixture and the inner one walks")
    lines.append("/// the expanded reaction list in cantera's order.")
    lines.append(
        "pub static NET_RATES: &[&[f64; %d]] = &[" % gas.n_reactions
    )
    for case_index, (temperature, pressure) in enumerate(CASES):
        fractions = scaled_fractions(FRACTIONS[case_index % n_fractions])
        composition = full_composition(fractions, molecules, gas)
        gas.TPX = temperature, pressure, composition
        rates = [float(value) for value in gas.net_rates_of_progress]
        lines.append(
            "    &[%s]," % ", ".join(rust_float(value) for value in rates)
        )
    lines.append("];")
    lines.append("")
    lines.append("/// the source digest the fixture was generated from.")
    lines.append('pub const SOURCE_SHA256: &str = "%s";' % digest)
    lines.append("")

    (CORE / "gri30_netrate_fixture.rs").write_text("\n".join(lines))
    print("mixtures %d reactions %d" % (count, gas.n_reactions))
    print("wrote gri30_netrate_fixture.rs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
