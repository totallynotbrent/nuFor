#!/usr/bin/env python3
"""Generate the nuFor GRI-Mech 3.0 transport table from Cantera.

usage:

    python3 tools/gen_gri30_transport.py [yaml_path]

the yaml path defaults to the gri30.yaml shipped with cantera 3.2.0.
one file is written:

    crates/nufor-core/src/gri30_transport_generated.rs

the output is deterministic: the same inputs give a byte-identical file,
because every floating point value is emitted with python's shortest
round-tripping repr and nothing carries a timestamp.

what the table holds, and why:

    each species contributes a lennard-jones diameter and well depth
    for the chapman-enskog collision integral, the polarizability and
    dipole moment for the monatomic and polar corrections, the
    rotational relaxation number for the diffusion collision integral,
    and the shape of the molecule.

    the table is the transport half of the gri-mech 3.0 database that
    the combustion lane already uses for its nine species. the values
    agree exactly with the hand-written table in combustion_transport.rs
    for the species both cover, which is what makes the fifty-four-row
    extension a continuation of the same source rather than a new
    dataset.

    the quantum-corrected well depths of hydrogen and helium are
    carried as cantera stores them: h2 has the celsius correction
    applied, so its epsilon differs from the classical lennard-jones
    value by the amount cantera's polynomial fits describe.

unit conventions:

    diameter                  angstrom
    well depth               kelvin, divided by boltzmann beforehand
    polarizability           cubic angstrom
    dipole                   debye
    rotational relaxation    dimensionless
"""

import hashlib
import pathlib
import sys

DEFAULT_YAML = (
    "plans/combustion_research/sources/gri30.yaml"
)

NA_PER_ANGSTROM = 1.0e-10
DEBYE_SI = 3.3356409519815204e-30

HEADER = """\
// generated by tools/gen_gri30_transport.py, do not edit.
//
// source mechanism: gri30.yaml from cantera 3.2.0.
// source sha256: {sha}
//
// each row is one species' transport data:
///
///   diameter          collision diameter, angstrom
///   well_depth        lennard-jones epsilon over boltzmann, kelvin
///   polarizability    volume polarizability, cubic angstrom
///   dipole            permanent dipole moment, debye
///   rot_relax         rotational relaxation number
///
/// the shape tells the collision-integral code whether the species is
/// an atom, a linear molecule, or something nonlinear.
"""


def find_yaml(explicit):
    """locate the mechanism file, preferring the argument."""
    if explicit:
        return pathlib.Path(explicit)
    repo_root = pathlib.Path(__file__).resolve().parents[1]
    candidates = [
        repo_root / DEFAULT_YAML,
        pathlib.Path(
            "/home/ebarleb/.local/lib/python3.12/site-packages/"
            "cantera/data/gri30.yaml"
        ),
        pathlib.Path("/usr/share/cantera/data/gri30.yaml"),
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate
    raise SystemExit(
        "cannot find gri30.yaml; pass its path as the first argument"
    )


def fmt(value):
    """emit a float so the same value reproduces exactly."""
    if value is None:
        return "f64::NAN"
    return repr(float(value))


def main(argv):
    yaml_path = find_yaml(argv[1] if len(argv) > 1 else None)
    digest = hashlib.sha256(yaml_path.read_bytes()).hexdigest()

    sys.path.insert(0, "/home/ebarleb/.local/lib/python3.12/site-packages")
    import cantera as ct

    gas = ct.Solution(str(yaml_path))

    lines = []
    for index in range(gas.n_species):
        species = gas.species(index)
        transport = species.transport
        geometry = transport.geometry or ""
        shape = {
            "atom": "Atom",
            "linear": "Linear",
            "nonlinear": "Nonlinear",
        }.get(geometry)
        if shape is None:
            raise SystemExit(
                f"species {species.name} has unknown geometry {geometry!r}"
            )

        diameter = transport.diameter
        well_depth = transport.well_depth
        polarizability = transport.polarizability
        dipole = transport.dipole
        rot_relax = transport.rotational_relaxation

        if diameter is None or well_depth is None:
            raise SystemExit(
                f"species {species.name} lacks lennard-jones data"
            )
        if polarizability is None:
            polarizability = 0.0
        if dipole is None:
            dipole = 0.0
        if rot_relax is None:
            rot_relax = 0.0

        diameter_ang = diameter / NA_PER_ANGSTROM
        well_depth_k = well_depth / 1.380649e-23
        polarizability_ang3 = (
            polarizability / NA_PER_ANGSTROM ** 3
        )
        dipole_debye = dipole / DEBYE_SI

        lines.append(
            "    TransportRow { "
f'name: "{species.name}", '
            f"shape: Shape::{shape}, "
            f"diameter: {fmt(diameter_ang)}, "
            f"well_depth: {fmt(well_depth_k)}, "
            f"polarizability: {fmt(polarizability_ang3)}, "
            f"dipole: {fmt(dipole_debye)}, "
            f"rot_relax: {fmt(rot_relax)} "
            "},"
        )

    body = HEADER.format(sha=digest)
    body += """
use super::gri30_thermo::NS_GRI30;

/// the shape of a molecule, which selects the collision integral.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Shape {
    /// a single atom.
    Atom,
    /// a diatomic or other molecule whose rotational degrees of freedom
    /// are linear.
    Linear,
    /// a molecule with bent geometry.
    Nonlinear,
}

/// one species' transport data.
#[derive(Clone, Copy, Debug)]
pub struct TransportRow {
    /// the species name, as the mechanism spells it.
    pub name: &'static str,
    /// the molecular shape.
    pub shape: Shape,
    /// the lennard-jones collision diameter, angstrom.
    pub diameter: f64,
    /// the lennard-jones well depth over boltzmann, kelvin.
    pub well_depth: f64,
    /// the volume polarizability, cubic angstrom.
    pub polarizability: f64,
    /// the permanent dipole moment, debye.
    pub dipole: f64,
    /// the rotational relaxation number.
    pub rot_relax: f64,
}

/// every species' transport data, in the mechanism's own order.
pub const TRANSPORT_ROWS: [TransportRow; NS_GRI30] = [
"""
    body += "\n".join(lines)
    body += "\n];\n"

    out_path = pathlib.Path(__file__).resolve().parents[1] / (
        "crates/nufor-core/src/gri30_transport_generated.rs"
    )
    out_path.write_text(body, encoding="utf-8")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main(sys.argv)
